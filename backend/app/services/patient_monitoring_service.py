"""
Patient Vital-Sign Monitoring and Risk Research Service.
EdgeShield AI.

Features:
- Physiological range validation & temperature unit conversion.
- Independent clinical data-quality flags.
- Missing measurement tracking.
- Experimental mortality risk estimation with mandatory disclaimers.
- Strict input validation rejecting NaN and infinity in direct feature payloads.
"""

import json
import logging
import math
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
import joblib
import numpy as np
import pandas as pd

from app.schemas.patient_monitoring import (
    ClinicalPredictionRequest,
    ClinicalPredictionResponse,
    MortalityRiskAssessmentRequest,
    MortalityRiskAssessmentResponse,
    VitalSignInput,
    VitalSignValidationResponse,
)

logger = logging.getLogger("edgeshield.patient_monitoring")

# Resolve research directory from workspace root or backend cwd
_CWD_RESEARCH = Path("research/patient_monitoring")
_ROOT_RESEARCH = Path(__file__).resolve().parents[3] / "research/patient_monitoring"
RESEARCH_DIR = _CWD_RESEARCH if _CWD_RESEARCH.exists() else _ROOT_RESEARCH

# Physiological clinical plausibility bounds
PLAUSIBLE_BOUNDS = {
    "heart_rate": (20.0, 260.0),
    "respiratory_rate": (0.0, 70.0),
    "spo2": (50.0, 100.0),
    "systolic_bp": (40.0, 280.0),
    "diastolic_bp": (20.0, 180.0),
    "mean_bp": (25.0, 200.0),
    "temperature_celsius": (30.0, 43.5),
}

CORE_VITALS = [
    "heart_rate",
    "respiratory_rate",
    "spo2",
    "systolic_bp",
    "diastolic_bp",
    "mean_bp",
    "temperature_celsius",
]

MANDATORY_DISCLAIMER = (
    "DISCLAIMER: This experimental risk estimate is generated by an exploratory baseline model trained on the "
    "MIMIC-IV Demo research dataset. It is strictly for educational, pipeline verification, and "
    "engineering demonstration purposes. It has NOT been clinically validated, is not an FDA-cleared "
    "medical device, and must NEVER be used for clinical diagnosis, patient management, or triage."
)

CLINICAL_LIMITATIONS = [
    "Trained on a 100-patient development dataset with only 14 unique positive mortality cases.",
    "High metric volatility: small sample size produces wide confidence intervals; generalizability is unverified.",
    "Target is eventual post-24h in-hospital mortality among eligible ICU stays, not near-term deterioration.",
    "Predictive features are restricted to non-invasive vital signs without lab or pharmacological variables.",
]


class PatientMonitoringService:
    def __init__(self, research_dir: Path = RESEARCH_DIR):
        self.research_dir = research_dir
        self.model = None
        self.feature_metadata = None
        self.cohort_summary = None
        self._load_artifacts()

    def _load_artifacts(self):
        """Safely load baseline model and cohort metadata if available."""
        model_path = self.research_dir / "baseline_model.joblib"
        meta_path = self.research_dir / "model_feature_metadata.json"
        cohort_path = self.research_dir / "cohort_audit_summary.json"

        self.model = None
        self.feature_metadata = None
        self.cohort_summary = None

        if model_path.exists():
            try:
                self.model = joblib.load(model_path)
                logger.info("Loaded patient monitoring baseline model from %s", model_path)
            except Exception as e:
                logger.warning("Failed to load baseline model: %s", e)
                self.model = None

        if meta_path.exists():
            try:
                with open(meta_path, "r") as f:
                    self.feature_metadata = json.load(f)
            except Exception as e:
                logger.warning("Failed to load feature metadata: %s", e)
                self.feature_metadata = None

        # Validate that model features and metadata match
        if self.model is not None and self.feature_metadata is not None:
            meta_features = self.feature_metadata.get("features", [])
            if hasattr(self.model, "feature_names_in_"):
                if list(self.model.feature_names_in_) != meta_features:
                    logger.warning(
                        "Metadata feature schema mismatch with model.feature_names_in_: "
                        "model has %d, metadata has %d. Deactivating model.",
                        len(self.model.feature_names_in_),
                        len(meta_features),
                    )
                    self.model = None

        if cohort_path.exists():
            try:
                with open(cohort_path, "r") as f:
                    self.cohort_summary = json.load(f)
            except Exception as e:
                logger.warning("Failed to load cohort summary: %s", e)

    def reload_artifacts(self, custom_dir: Optional[Path] = None):
        """Allows tests or runtime to refresh artifacts from path."""
        if custom_dir is not None:
            self.research_dir = custom_dir
        self._load_artifacts()

    def validate_vital_signs(self, vitals: VitalSignInput) -> VitalSignValidationResponse:
        """Validate input units, plausible clinical bounds, and identify missing/flagged measurements."""
        messages: List[str] = []
        quality_flags: List[str] = []
        missing: List[str] = []

        # Temperature normalization
        temp_c: Optional[float] = None
        if vitals.temperature is not None:
            unit = vitals.temperature_unit.strip().upper()
            if unit in ["F", "FAHRENHEIT"]:
                temp_c = round((vitals.temperature - 32.0) * 5.0 / 9.0, 2)
                messages.append(f"Temperature converted from {vitals.temperature}°F to {temp_c}°C.")
            else:
                temp_c = round(vitals.temperature, 2)

        # Check each vital against bounds and missingness
        v_dict = {
            "heart_rate": vitals.heart_rate,
            "respiratory_rate": vitals.respiratory_rate,
            "spo2": vitals.spo2,
            "systolic_bp": vitals.systolic_bp,
            "diastolic_bp": vitals.diastolic_bp,
            "mean_bp": vitals.mean_bp,
            "temperature_celsius": temp_c,
        }

        for v_name, val in v_dict.items():
            if val is None:
                missing.append(v_name)
                continue

            # Check for non-finite values
            if math.isnan(val) or math.isinf(val):
                raise ValueError(f"Invalid non-finite value provided for {v_name}")

            vmin, vmax = PLAUSIBLE_BOUNDS[v_name]
            if val < vmin or val > vmax:
                messages.append(
                    f"Warning: {v_name} value ({val}) is outside standard physiological range ({vmin}-{vmax})."
                )

        # Specific quality flags matching MIMIC-IV research rules
        if vitals.heart_rate == 0 or vitals.respiratory_rate == 0:
            quality_flags.append("review_zero_value")
            messages.append("Flag: Zero heart-rate or respiratory-rate recorded.")

        if vitals.spo2 is not None and vitals.spo2 < 70.0:
            quality_flags.append("review_low_spo2")
            messages.append("Flag: Severe hypoxemia (< 70% SpO2) detected.")

        if vitals.heart_rate is not None and (vitals.heart_rate < 30.0 or vitals.heart_rate > 180.0):
            quality_flags.append("review_extreme_heart_rate")
            messages.append(f"Flag: Extreme heart rate ({vitals.heart_rate} bpm) requiring clinical review.")

        return VitalSignValidationResponse(
            valid=True,
            temperature_celsius=temp_c,
            validation_messages=messages,
            quality_flags=quality_flags,
            missing_measurements=missing,
        )

    def _build_feature_row(
        self,
        vitals: Optional[VitalSignInput] = None,
        features: Optional[Dict[str, float]] = None,
        hours_monitored: float = 24.0,
    ) -> Tuple[pd.DataFrame, List[str], List[str], Dict[str, Optional[float]]]:
        """
        Builds a 1-row feature DataFrame strictly aligned with expected model features.
        Rejects NaN and infinity in features dict, while passing missing values as NaN
        so the fitted median imputer handles them safely.
        """
        expected_features: List[str] = self.feature_metadata.get("features", [])
        feature_dict: Dict[str, float] = {}
        quality_flags: List[str] = []
        missing_fields: List[str] = []
        v_dict: Dict[str, Optional[float]] = {}

        if features is not None:
            # Check for unexpected features outside expected model feature schema
            unknown_features = [k for k in features.keys() if k not in expected_features]
            if unknown_features:
                raise ValueError(
                    f"Unexpected feature(s) provided: {', '.join(sorted(unknown_features)[:5])}. "
                    "Features must match the expected 69 clinical feature schema."
                )

            # Direct feature dictionary payload
            for k, val in features.items():
                if val is not None and (math.isnan(val) or math.isinf(val)):
                    raise ValueError(f"Feature '{k}' contains non-finite number (NaN or Infinity).")

            for feat in expected_features:
                if feat in features and features[feat] is not None:
                    feature_dict[feat] = float(features[feat])
                else:
                    feature_dict[feat] = np.nan
                    missing_fields.append(feat)

        elif vitals is not None:
            # Vital sign input mapping
            val_res = self.validate_vital_signs(vitals)
            quality_flags = val_res.quality_flags
            missing_fields = val_res.missing_measurements

            v_dict = {
                "heart_rate": vitals.heart_rate,
                "respiratory_rate": vitals.respiratory_rate,
                "spo2": vitals.spo2,
                "systolic_bp": vitals.systolic_bp,
                "diastolic_bp": vitals.diastolic_bp,
                "mean_bp": vitals.mean_bp,
                "temperature_celsius": val_res.temperature_celsius,
            }

            # Summary indicators
            feature_dict["flag_zero_value_count"] = 1.0 if "review_zero_value" in quality_flags else 0.0
            feature_dict["flag_low_spo2_count"] = 1.0 if "review_low_spo2" in quality_flags else 0.0
            feature_dict["flag_extreme_hr_count"] = 1.0 if "review_extreme_heart_rate" in quality_flags else 0.0
            feature_dict["total_flagged_observations"] = float(len(quality_flags))
            feature_dict["distinct_monitored_hours"] = float(min(hours_monitored, 24.0))

            present_count = sum(1 for v in v_dict.values() if v is not None)
            feature_dict["total_vital_measurements"] = float(present_count * 20)

            for v in CORE_VITALS:
                val = v_dict.get(v)
                if val is not None:
                    feature_dict[f"{v}_count"] = 24.0
                    feature_dict[f"{v}_is_missing"] = 0.0
                    feature_dict[f"{v}_recent"] = float(val)
                    feature_dict[f"{v}_mean"] = float(val)
                    feature_dict[f"{v}_min"] = float(val)
                    feature_dict[f"{v}_max"] = float(val)
                    feature_dict[f"{v}_std"] = 0.0
                    feature_dict[f"{v}_time_since_last_h"] = 0.5
                    feature_dict[f"{v}_trend_late_minus_early"] = 0.0
                else:
                    feature_dict[f"{v}_count"] = 0.0
                    feature_dict[f"{v}_is_missing"] = 1.0
                    feature_dict[f"{v}_recent"] = np.nan
                    feature_dict[f"{v}_mean"] = np.nan
                    feature_dict[f"{v}_min"] = np.nan
                    feature_dict[f"{v}_max"] = np.nan
                    feature_dict[f"{v}_std"] = np.nan
                    feature_dict[f"{v}_time_since_last_h"] = 24.0
                    feature_dict[f"{v}_trend_late_minus_early"] = np.nan
        else:
            raise ValueError("Either 'vitals' or 'features' must be provided.")

        instance_df = pd.DataFrame([{f: feature_dict.get(f, np.nan) for f in expected_features}])
        return instance_df, quality_flags, missing_fields, v_dict

    def assess_risk(self, request: MortalityRiskAssessmentRequest) -> MortalityRiskAssessmentResponse:
        """Produce an experimental risk estimate with mandatory disclaimers and limitations."""
        if request.vitals is None and request.features is None:
            raise ValueError("Either 'vitals' or 'features' must be provided in request payload.")

        # Handle model unavailable
        if self.model is None or self.feature_metadata is None:
            v_dict: Dict[str, Optional[float]] = {}
            q_flags: List[str] = []
            m_list: List[str] = []
            if request.vitals:
                val_res = self.validate_vital_signs(request.vitals)
                q_flags = val_res.quality_flags
                m_list = val_res.missing_measurements
                v_dict = {
                    "heart_rate": request.vitals.heart_rate,
                    "respiratory_rate": request.vitals.respiratory_rate,
                    "spo2": request.vitals.spo2,
                    "systolic_bp": request.vitals.systolic_bp,
                    "diastolic_bp": request.vitals.diastolic_bp,
                    "mean_bp": request.vitals.mean_bp,
                    "temperature_celsius": val_res.temperature_celsius,
                }
            return MortalityRiskAssessmentResponse(
                prediction=None,
                estimated_probability=None,
                risk_score=None,
                risk_category="INDETERMINATE",
                model_name="UNAVAILABLE",
                model_version="unavailable",
                prediction_target="hospital_expire_flag",
                prediction_horizon="post-24h in-hospital stay among eligible cohort",
                experimental_research_only=True,
                clinical_disclaimer=MANDATORY_DISCLAIMER,
                limitations=CLINICAL_LIMITATIONS + ["Trained baseline model artifact not found on system path."],
                quality_flags=q_flags,
                missing_measurements=m_list,
                validated_vitals_celsius=v_dict,
            )

        instance_df, q_flags, m_fields, v_dict = self._build_feature_row(
            vitals=request.vitals,
            features=request.features,
            hours_monitored=request.hours_monitored,
        )

        try:
            prob = float(self.model.predict_proba(instance_df)[0, 1])
            risk_score = round(prob, 4)
            prediction = int(risk_score >= 0.5)

            if risk_score < 0.20:
                category = "LOW"
            elif risk_score < 0.45:
                category = "ELEVATED"
            else:
                category = "HIGH"
        except Exception as e:
            logger.error("Error evaluating baseline model: %s", e)
            risk_score = None
            prediction = None
            category = "INDETERMINATE"

        return MortalityRiskAssessmentResponse(
            prediction=prediction,
            estimated_probability=risk_score,
            risk_score=risk_score,
            risk_category=category,
            model_name="LogisticRegression(L2, C=0.1)",
            model_version="1.0.0-mimic4-demo-baseline",
            prediction_target="hospital_expire_flag",
            prediction_horizon="post-24h in-hospital stay among eligible cohort",
            experimental_research_only=True,
            clinical_disclaimer=MANDATORY_DISCLAIMER,
            limitations=CLINICAL_LIMITATIONS,
            quality_flags=q_flags,
            missing_measurements=m_fields,
            validated_vitals_celsius=v_dict,
        )

    def predict_clinical_outcome(self, request: ClinicalPredictionRequest) -> ClinicalPredictionResponse:
        """Standardized prediction endpoint matching requested Phase B response schema."""
        if request.vitals is None and request.features is None:
            raise ValueError("Either 'vitals' or 'features' must be provided in request payload.")

        if self.model is None or self.feature_metadata is None:
            return ClinicalPredictionResponse(
                prediction=None,
                estimated_probability=None,
                risk_category="INDETERMINATE",
                model_name="UNAVAILABLE",
                prediction_target="hospital_expire_flag",
                prediction_horizon="post-24h in-hospital stay among eligible cohort",
                experimental_research_only=True,
                clinical_disclaimer=MANDATORY_DISCLAIMER,
                limitations=CLINICAL_LIMITATIONS + ["Model artifact unavailable."],
                missing_features=[],
                quality_flags=[],
            )

        instance_df, q_flags, m_fields, _ = self._build_feature_row(
            vitals=request.vitals,
            features=request.features,
            hours_monitored=request.hours_monitored,
        )

        try:
            prob = float(self.model.predict_proba(instance_df)[0, 1])
            prob_val = round(prob, 4)
            prediction = int(prob_val >= 0.5)

            if prob_val < 0.20:
                cat = "LOW"
            elif prob_val < 0.45:
                cat = "ELEVATED"
            else:
                cat = "HIGH"
        except Exception as e:
            logger.error("Error running clinical prediction: %s", e)
            prob_val = None
            prediction = None
            cat = "INDETERMINATE"

        return ClinicalPredictionResponse(
            prediction=prediction,
            estimated_probability=prob_val,
            risk_category=cat,
            model_name="LogisticRegression(L2, C=0.1)",
            prediction_target="hospital_expire_flag",
            prediction_horizon="post-24h in-hospital stay among eligible cohort",
            experimental_research_only=True,
            clinical_disclaimer=MANDATORY_DISCLAIMER,
            limitations=CLINICAL_LIMITATIONS,
            missing_features=m_fields,
            quality_flags=q_flags,
        )

    def get_cohort_summary(self) -> Dict[str, Any]:
        """Return the verified cohort audit and model metrics."""
        summary = self.cohort_summary or {}
        metrics_file = self.research_dir / "model_metrics.json"
        if metrics_file.exists():
            try:
                with open(metrics_file, "r") as f:
                    summary["model_metrics"] = json.load(f)
            except Exception:
                pass
        return summary


# Global singleton instance
patient_monitoring_service = PatientMonitoringService()
